// Builds supabase/tests/20261120_packages_all_dryrun.sql: ONE file to paste into the Supabase SQL Editor that runs the
// packages schema, the C1 RPCs, the payment RPCs and every probe in a single transaction that always ends in ROLLBACK
// (nothing is committed anywhere, the DDL included).
//
//   node scripts/build-packages-dryrun.mjs                          write the file (without the Wave 1 migration)
//   node scripts/build-packages-dryrun.mjs --with-client-settings   also embed 20261119_client_settings.sql first
//                                                                   (only if client_settings is not live yet)
//   node scripts/build-packages-dryrun.mjs --check                  exit 1 when the committed file is stale
//
// The inputs are read verbatim; the script only strips the probe files' own begin/rollback pair and ALL PASS rows
// (the combined file has exactly one of each at the end) and refuses to build if an input would end the transaction early.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const args = new Set(process.argv.slice(2));
const withClientSettings = args.has("--with-client-settings");
const checkOnly = args.has("--check");

const OUTPUT = "supabase/tests/20261120_packages_all_dryrun.sql";

const migrations = [
  ...(withClientSettings ? ["supabase/migrations/20261119_client_settings.sql"] : []),
  "supabase/migrations/20261120_packages_schema.sql",
  "supabase/migrations/20261120_packages_rpcs.sql",
  "supabase/migrations/20261120_packages_payment_rpcs.sql",
];
const probes = [
  { file: "supabase/tests/20261120_packages_probes.sql", label: "C1 probes" },
  { file: "supabase/tests/20261120_packages_payment_probes.sql", label: "payment probes" },
];

function read(file) {
  const path = resolve(root, file);
  if (!existsSync(path)) {
    throw new Error(`Missing input file: ${file}`);
  }
  return readFileSync(path, "utf8").replace(/\r\n/g, "\n");
}

/** Statement-level transaction control that would break the single-transaction guarantee (comments ignored). */
function assertNoTransactionControl(file, text) {
  text.split("\n").forEach((line, index) => {
    const code = line.replace(/--.*$/, "");
    if (/^\s*(commit|rollback|abort|start\s+transaction|begin)\s*(work|transaction)?\s*;/i.test(code)) {
      throw new Error(`${file}:${index + 1} contains transaction control (${line.trim()}); the dry run must never commit`);
    }
  });
}

const parts = [];
parts.push(`-- =====================================================================================================================
-- Packages ALL-IN-ONE DRY RUN (quick-261114-22k, Wave 3). GENERATED by scripts/build-packages-dryrun.mjs: do not edit.
-- =====================================================================================================================
-- ONE transaction: ${migrations.map((file) => file.split("/").pop()).join(", ")}, then the C1 probes and the
-- payment probes. It ends in ROLLBACK, so nothing is committed, the DDL included. There is no COMMIT anywhere in this
-- file (the generator refuses to build one).
--
-- HOW TO RUN: Supabase Dashboard -> SQL Editor, as the default postgres role. Paste this WHOLE file and run it once.
--   Expected: the last result is one row 'ALL PASS'. Any failure aborts with 'FAIL: <what>' (the transaction is then
--   rolled back automatically when the editor session ends; if the editor keeps the failed transaction open, run
--   ROLLBACK; by itself).
--   Pick a quiet moment: the DDL holds an exclusive lock on public.appointments until the rollback (a few seconds).
--   It borrows the first two clients with different crm_user_id values and inserts throwaway rows (rolled back).
--   Regenerate after any input changes:  node scripts/build-packages-dryrun.mjs${withClientSettings ? " --with-client-settings" : ""}
--   Staleness check:                      node scripts/build-packages-dryrun.mjs --check${withClientSettings ? " --with-client-settings" : ""}
-- =====================================================================================================================

begin;
`);

for (const file of migrations) {
  const text = read(file);
  assertNoTransactionControl(file, text);
  parts.push(`-- ---------------------------------------------------------------------------------------------------------------------
-- >>> BEGIN ${file}
-- ---------------------------------------------------------------------------------------------------------------------
${text.trimEnd()}
-- >>> END ${file}
`);
}

for (const { file, label } of probes) {
  const text = read(file);
  const lines = text.split("\n");
  const beginIndexes = lines.map((line, index) => (/^begin;\s*$/.test(line) ? index : -1)).filter((index) => index >= 0);
  const rollbackIndexes = lines.map((line, index) => (/^rollback;\s*$/.test(line) ? index : -1)).filter((index) => index >= 0);
  const passIndexes = lines.map((line, index) => (/^select 'ALL PASS' as result;\s*$/.test(line) ? index : -1)).filter((index) => index >= 0);
  if (beginIndexes.length !== 1 || rollbackIndexes.length !== 1 || passIndexes.length !== 1) {
    throw new Error(`${file}: expected exactly one top-level begin;, rollback; and ALL PASS row`);
  }

  const body = lines
    .map((line, index) => {
      if (index === beginIndexes[0] || index === rollbackIndexes[0]) return null;
      if (index === passIndexes[0]) return `do $$ begin raise notice '${label} passed'; end $$;`;
      return line;
    })
    .filter((line) => line !== null)
    .join("\n");
  assertNoTransactionControl(file, body);
  parts.push(`-- ---------------------------------------------------------------------------------------------------------------------
-- >>> BEGIN ${file} (its own begin; and rollback; removed)
-- ---------------------------------------------------------------------------------------------------------------------
${body.trimEnd()}
-- >>> END ${file}
`);
}

parts.push(`reset role;
select 'ALL PASS' as result;

rollback;
`);

const output = parts.join("\n");

// Final guarantees on the generated text itself.
assertNoTransactionControl(OUTPUT, output.replace(/^begin;$/m, "-- begin;").replace(/^rollback;$/m, "-- rollback;"));
const rollbackCount = (output.match(/^rollback;\s*$/gm) ?? []).length;
const beginCount = (output.match(/^begin;\s*$/gm) ?? []).length;
if (rollbackCount !== 1 || beginCount !== 1 || !/rollback;\s*$/.test(output) || /^\s*commit\b/im.test(output)) {
  throw new Error("Generated file must contain exactly one begin;, exactly one trailing rollback; and no commit");
}

const outputPath = resolve(root, OUTPUT);
if (checkOnly) {
  const current = existsSync(outputPath) ? readFileSync(outputPath, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== output) {
    console.error(`${OUTPUT} is stale: run node scripts/build-packages-dryrun.mjs${withClientSettings ? " --with-client-settings" : ""}`);
    process.exit(1);
  }
  console.log(`build-packages-dryrun: ${OUTPUT} is up to date`);
} else {
  writeFileSync(outputPath, output, "utf8");
  console.log(`build-packages-dryrun: wrote ${OUTPUT} (${output.split("\n").length} lines, ${migrations.length} migrations, ${probes.length} probe files, no commit)`);
}
